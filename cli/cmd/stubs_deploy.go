// ----------------------------------------------------------------------
// renderTemplate is a tiny wrapper around text/template that returns
// the rendered string. It panics on a bad template (these are author-
// time strings, so a panic surfaces the bug immediately during ` + "`go test`" + `).
// ----------------------------------------------------------------------

func renderTemplate(name, body string, opts ScaffoldOptions) (string, error) {
	tmpl, err := template.New(name).Parse(body)
	if err != nil {
		return "", fmt.Errorf("scaffold: parse %s: %w", name, err)
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, opts); err != nil {
		return "", fmt.Errorf("scaffold: execute %s: %w", name, err)
	}
	return buf.String(), nil
}

// envStubWithInfra builds the .env body conditional on the picked
// infrastructure. Replaces the older `envStub(name)` for new
// projects; the legacy stub stays for backward compatibility.
func envStubWithInfra(opts ScaffoldOptions) string {
	var b strings.Builder
	fmt.Fprintf(&b, "APP_NAME=%s\nAPP_ENV=local\nAPP_DEBUG=true\nAPP_ADDR=:8080\n\n", opts.Name)
	switch opts.Database {
	case "postgres":
		fmt.Fprintf(&b, "# Postgres (matches docker-compose.yml)\n")
		fmt.Fprintf(&b, "DB_CONNECTION=postgres\nDB_HOST=127.0.0.1\nDB_PORT=5432\n")
		fmt.Fprintf(&b, "DB_USERNAME=app\nDB_PASSWORD=secret\nDB_DATABASE=%s\n", opts.Name)
		fmt.Fprintf(&b, "DB_SSL_MODE=disable\n\n")
	case "mysql":
		fmt.Fprintf(&b, "# MySQL (matches docker-compose.yml)\n")
		fmt.Fprintf(&b, "DB_CONNECTION=mysql\nDB_HOST=127.0.0.1\nDB_PORT=3306\n")
		fmt.Fprintf(&b, "DB_USERNAME=app\nDB_PASSWORD=secret\nDB_DATABASE=%s\n\n", opts.Name)
	case "sqlite":
		fmt.Fprintf(&b, "DB_CONNECTION=sqlite\nDB_DATABASE=app.db\n\n")
	}
	if opts.Cache == "redis" {
		fmt.Fprintf(&b, "# Redis (cache / broadcasting / queue)\nREDIS_ADDR=127.0.0.1:6379\n\n")
	}
	if opts.Storage == "minio" {
		fmt.Fprintf(&b, "# MinIO (S3-compatible)\n")
		fmt.Fprintf(&b, "S3_ENDPOINT=127.0.0.1:9000\nS3_ACCESS_KEY=minioadmin\nS3_SECRET_KEY=minioadmin\n")
		fmt.Fprintf(&b, "S3_BUCKET=%s\nS3_USE_SSL=false\n\n", opts.Name)
	}
	fmt.Fprintf(&b, "JWT_SECRET=please-change-this-to-a-strong-random-secret\n")
	fmt.Fprintf(&b, "# Generated by `lago key:generate`:\nAPP_KEY=\n")
	return b.String()
}
