// ScaffoldOptions captures every interactive choice `lago new` made.
// The deploy/code stubs are conditional on these fields so the
// generated project only carries services it actually uses.
type ScaffoldOptions struct {
	Name      string // app name, used in env / compose service name
	Module    string // Go module path
	Framework string // "web" | "gin"
	Database  string // "postgres" | "mysql" | "sqlite" | "none"
	Cache     string // "redis" | "none"
	Storage   string // "minio" | "none"
}

