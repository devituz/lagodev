const dockerfileTmpl = `# syntax=docker/dockerfile:1.7
# Multi-stage build. Final image runs as a non-root user on a
# distroless base — no shell, no package manager, smaller attack
# surface than alpine.

# --- build stage --------------------------------------------------------
FROM golang:1.25-alpine AS build
WORKDIR /src

# Pre-cache modules.
COPY go.mod go.sum* ./
RUN --mount=type=cache,target=/go/pkg/mod \
    go mod download

# Build a statically-linked binary.
COPY . .
ARG VERSION=dev
RUN --mount=type=cache,target=/go/pkg/mod \
    --mount=type=cache,target=/root/.cache/go-build \
    CGO_ENABLED=0 GOOS=linux \
    go build -trimpath -ldflags "-s -w -X main.version=${VERSION}" \
        -o /out/app .

# --- runtime stage ------------------------------------------------------
FROM gcr.io/distroless/static-debian12:nonroot
WORKDIR /app

# Copy the binary and the migrations / config directories the runtime
# may need at boot. Add other dirs (templates/, locales/, …) as needed.
COPY --from=build /out/app /app/app

USER nonroot:nonroot
EXPOSE 8080

ENV APP_ENV=production \
    APP_ADDR=:8080

ENTRYPOINT ["/app/app"]
`

